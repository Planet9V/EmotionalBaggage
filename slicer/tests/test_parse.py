import json

import pytest

from app import orca
from conftest import FIX


def test_statistics_bambu_sample():
    r = orca.read_statistics(FIX / "bambu_a1_cube.statistics.json")
    assert r.seconds == pytest.approx(1191.216)
    assert r.filament_mm == pytest.approx(1221.41)
    assert r.filament_g == pytest.approx(3.7017)
    assert r.layers == 100
    assert r.support_g == 0


def test_gcode_header_bambu_sample():
    r = orca.read_gcode_header((FIX / "bambu_a1_cube.gcode.txt").read_text())
    assert r.seconds == 19 * 60 + 51
    assert (r.filament_mm, r.filament_g, r.filament_cm3) == (1221.41, 3.70, 2.94)


def test_gcode_header_prusa_sample():
    r = orca.read_gcode_header((FIX / "prusa_mk4s_cube.gcode.txt").read_text())
    assert r.seconds == 14 * 60 + 23
    assert r.filament_g == 3.98


def test_both_sources_agree_on_the_real_samples():
    a = orca.read_statistics(FIX / "prusa_mk4s_cube.statistics.json")
    b = orca.read_gcode_header((FIX / "prusa_mk4s_cube.gcode.txt").read_text())
    assert abs(a.seconds - b.seconds) < 1
    assert a.filament_mm == pytest.approx(b.filament_mm)


@pytest.mark.parametrize("text,secs", [("1d 2h 3m 4s", 93784), ("2h", 7200), ("45s", 45), ("1h 5m", 3900)])
def test_duration(text, secs):
    assert orca.parse_duration(text) == secs


def test_duration_rejects_text():
    with pytest.raises(ValueError):
        orca.parse_duration("soon")


def test_header_without_numbers_is_an_error_not_a_guess():
    with pytest.raises(orca.SliceError):
        orca.read_gcode_header("; generated by OrcaSlicer\nG1 X1\n")
